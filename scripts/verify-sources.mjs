import Parser from "rss-parser";
const parser = new Parser();
const H = { "User-Agent": "Mozilla/5.0 (compatible; WireRoomBot/1.0; +https://wireroom.onrender.com)", Accept: "*/*" };
const get = async (u) => parser.parseString(await (await fetch(u, { headers: H, signal: AbortSignal.timeout(20000) })).text());
const sd = await get("https://travel.state.gov/_res/rss/TAsTWs.xml");
console.log("== STATE " + sd.items.map((i) => `${i.title.split(" - Level")[0]}|${(i.categories || []).find((c) => c.$?.domain === "Country-Tag")?._}|${(i.title.match(/Level (\d)/) || [])[1]}`).join(";;"));
const all = await get("https://www.cisa.gov/cybersecurity-advisories/all.xml");
const aa = all.items.filter((i) => /\/cybersecurity-advisories\/aa/i.test(i.link || ""));
console.log("== CISA AA count", aa.length, aa.slice(0, 5).map((i) => i.title).join(" || "));
const kinds = {}; for (const i of all.items) { const k = (i.link || "").split("/")[4] || "?"; kinds[k] = (kinds[k] || 0) + 1; } console.log("== CISA kinds", JSON.stringify(kinds));
const cc = await get("https://www.cyber.gc.ca/api/cccs/rss/v1/get?feed=alerts_advisories&lang=en");
const al = cc.items.filter((i) => /\(AL\d{2}-\d+\)/.test(i.title || ""));
console.log("== CCCS AL", al.length, al.slice(0, 5).map((i) => `${i.isoDate?.slice(0, 10)} ${i.title}`).join(" || "));
